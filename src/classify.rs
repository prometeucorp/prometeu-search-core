//! Reference path and source-header classification shared by graph analyses.
use regex::Regex;
use std::sync::LazyLock;

pub(crate) fn is_test_path(path: &str) -> bool {
    static SEPARATED: LazyLock<Regex> = LazyLock::new(|| {
        Regex::new(r"[._-](test|tests|unittest|unittests|spec|specs)\.[a-z0-9]+$").unwrap()
    });
    static CAMEL: LazyLock<Regex> = LazyLock::new(|| {
        Regex::new(r"(?:Test|Tests|TestCase|Tester|Spec|Specs)\.[A-Za-z0-9]+$").unwrap()
    });
    static SOURCE_SET: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(r"(?:^|/)[A-Za-z0-9]*(?:Test|Tests|Spec)/").unwrap());
    static SUPPORT: LazyLock<Regex> = LazyLock::new(|| {
        Regex::new(r"(?:^|/)(?:[A-Za-z0-9_.]+[-_]test(?:s|ing)?|testdata|testutils?|test[-_]utils?|fakes?|mocks?|__mocks__|stubs|unittests|[A-Za-z0-9_.]+[-_]unittests?)/").unwrap()
    });
    let lower = path.to_lowercase();
    let name = path.rsplit('/').next().unwrap_or(path);
    let lower_name = name.to_lowercase();
    lower_name.starts_with("test_")
        || lower_name.starts_with("test.")
        || SEPARATED.is_match(&lower_name)
        || CAMEL.is_match(name)
        || [
            "/tests/",
            "/test/",
            "/__tests__/",
            "/spec/",
            "/specs/",
            "/testlib/",
            "/testing/",
            "/e2e/",
        ]
        .iter()
        .any(|part| lower.contains(part))
        || ["test/", "tests/", "spec/", "specs/", "e2e/"]
            .iter()
            .any(|part| lower.starts_with(part))
        || SOURCE_SET.is_match(path)
        || SUPPORT.is_match(&lower)
}

pub(crate) fn is_test_file(path: &str) -> bool {
    if is_test_path(path) {
        return true;
    }
    let lower = path.to_lowercase();
    let scope = lower.find("/src/").map_or_else(
        || {
            if lower.starts_with("src/") {
                ""
            } else {
                &lower
            }
        },
        |at| &lower[..at + 1],
    );
    [
        "integration",
        "sample",
        "samples",
        "example",
        "examples",
        "fixture",
        "fixtures",
        "benchmark",
        "benchmarks",
        "demo",
        "demos",
    ]
    .iter()
    .any(|name| scope.starts_with(&format!("{name}/")) || scope.contains(&format!("/{name}/")))
}

pub(crate) fn generated_file(path: &str, source: &str) -> anyhow::Result<bool> {
    Ok(prometeu_extract::is_generated_file(path)
        || generated_header(source)?
        || prometeu_extract::is_minified_content(path, source))
}

fn generated_header(source: &str) -> anyhow::Result<bool> {
    // The reference's window is measured in UTF-16 units, not bytes.
    let end = source
        .char_indices()
        .scan(0, |units, (at, ch)| {
            *units += ch.len_utf16();
            Some((at, *units))
        })
        .find(|(_, units)| *units > 8192)
        .map_or(source.len(), |(at, _)| at);
    let head = &source[..end];
    if !head.to_ascii_lowercase().contains("generat") {
        return Ok(false);
    }
    static LEADER: LazyLock<Regex> = LazyLock::new(|| {
        Regex::new(r#"(?i)^[\t\n\x0B\x0C\r \u{A0}\u{1680}\u{2000}-\u{200A}\u{2028}\u{2029}\u{202F}\u{205F}\u{3000}\u{FEFF}]*(?://|/\*+|\*+/?|#+|--+|<!--|%+|;+|'|!|\(\*|\{-|"""|'''|=begin|<#|@rem(?-u:\b)|rem(?-u:\b))"#).unwrap()
    });
    static BANNERS: LazyLock<Vec<fancy_regex::Regex>> = LazyLock::new(|| {
        [
        r"(?i)\bcode generated\b.{0,200}?\bdo not edit\b",
        r"(?i)\b(?:automatically |auto[- ]?)?generated (?:by|from|with)\b.{0,200}?\bdo not (?:edit|modify|change)\b",
        r"(?:^|[^\p{L}\p{N}_@])@generated\b",
        r"(?i)<auto-?generated\s*/?>",
        r"(?i)\b(?:automatically generated|auto[- ]?generated|autogenerated) by\b",
        r"(?i)\bgenerated by\s+\S.{0,80}?\bby running\b",
        r"(?i)\bthis (?:file|class|code|module) (?:is|was) (?:auto[- ]?)?generated\b",
        r"(?i)\bdo not (?:edit|modify)\b.{0,120}?\b(?:auto[- ]?generated|generated file|generated code)\b",
    ].iter().map(|pattern| fancy_regex::Regex::new(&crate::parser::javascript_regex::pattern(pattern)).unwrap()).collect()
    });
    let mut open_block: Option<&str> = None;
    for line in head.split('\n').take(60) {
        if open_block.is_some() || LEADER.is_match(line) {
            for pattern in BANNERS.iter() {
                if pattern.is_match(line)? {
                    return Ok(true);
                }
            }
        }
        if let Some(close) = open_block {
            if line.contains(close) {
                open_block = None;
            }
            continue;
        }
        for (open, close) in [
            ("/*", "*/"),
            ("<!--", "-->"),
            ("\"\"\"", "\"\"\""),
            ("'''", "'''"),
            ("=begin", "=end"),
            ("<#", "#>"),
        ] {
            if let Some(at) = line.find(open) {
                if !line[at + open.len()..].contains(close) {
                    open_block = Some(close);
                }
                break;
            }
        }
    }
    Ok(false)
}

pub(crate) fn is_test_suite_path(path: &str) -> anyhow::Result<bool> {
    if !is_test_path(path) {
        return Ok(false);
    }
    let lower = path.to_lowercase();
    let name = lower.rsplit('/').next().unwrap_or("");
    let original = path.rsplit('/').next().unwrap_or("");
    Ok(name.starts_with("test_")
        || name == "conftest.py"
        || crate::frameworks::source_pattern(
            r"[._-](?:test|tests|unittest|unittests)\.[a-z0-9]+$|[._](?:spec|specs)\.[a-z0-9]+$",
        )?
        .is_match(name)?
        || crate::frameworks::source_pattern(
            r"(?:Test|Tests|TestCase)\.(?:java|kt|kts|swift|cs|scala|groovy|m|mm|vb|fs)$",
        )?
        .is_match(original)?
        || crate::frameworks::source_pattern(
            r"(?:^|/)(?:tests?|__tests__|specs?|e2e|unittests|[\w.]+[-_]unittests?)/",
        )?
        .is_match(&lower)?
        || crate::frameworks::source_pattern(r"(?:^|/)[A-Za-z0-9]*(?:Test|Tests|Spec)/")?
            .is_match(path)?)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn classifications_match_independent_reference() {
        let fixture: serde_json::Value = serde_json::from_str(include_str!(
            "../tests/fixtures/upstream/analysis/classification.json"
        ))
        .unwrap();
        for case in fixture["paths"].as_array().unwrap() {
            let path = case["path"].as_str().unwrap();
            assert_eq!(is_test_path(path), case["testPath"], "{path}");
            assert_eq!(is_test_file(path), case["testFile"], "{path}");
            assert_eq!(
                prometeu_extract::is_generated_file(path),
                case["generatedPath"],
                "{path}"
            );
        }
        for case in fixture["sources"].as_array().unwrap() {
            let source = case["source"].as_str().unwrap();
            assert_eq!(
                generated_header(source).unwrap(),
                case["header"],
                "{source:?}"
            );
            assert_eq!(
                generated_file("bundle.js", source).unwrap(),
                case["generated"],
                "{source:?}"
            );
        }
    }
}
